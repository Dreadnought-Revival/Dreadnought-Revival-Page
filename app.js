(function () {
  "use strict";

  // Mobile nav toggle
  var toggle = document.querySelector(".nav-toggle");
  var links = document.getElementById("nav-links");
  if (toggle && links) {
    toggle.addEventListener("click", function () {
      var open = links.classList.toggle("open");
      toggle.setAttribute("aria-expanded", open ? "true" : "false");
    });
  }

  // Server status badge: static fallback, upgraded if data/server-status.json exists
  function loadStatus() {
    var badge = document.getElementById("status-badge");
    var detail = document.getElementById("status-detail");
    if (!badge) return;
    fetch("data/server-status.json")
      .then(function (r) {
        if (!r.ok) throw new Error("no status file");
        return r.json();
      })
      .then(function (s) {
        badge.textContent = s.online ? "Online" : "Offline";
        badge.classList.add(s.online ? "online" : "offline");
        if (typeof s.players === "number") {
          detail.textContent = s.players + " player" + (s.players === 1 ? "" : "s") + " online" +
            (s.updated_at ? " (updated " + s.updated_at + ")" : "");
        }
      })
      .catch(function () {
        badge.textContent = "Community-run";
        detail.textContent = "Live status is reported by the community — see the links below.";
      });
  }

  // Patch notes: rendered from data/patch-notes.json (generated by the update-patch-notes workflow)
  var state = { entries: [], filter: "all" };

  function dayLabel(iso) {
    var d = new Date(iso);
    return d.toLocaleDateString(undefined, { year: "numeric", month: "short", day: "numeric", timeZone: "UTC" });
  }

  function render() {
    var host = document.getElementById("patch-notes-list");
    if (!host) return;
    var entries = state.entries.filter(function (e) {
      return state.filter === "all" || e.repo === state.filter;
    });
    if (!entries.length) {
      host.innerHTML = '<p class="muted">No patch notes yet.</p>';
      return;
    }
    var byDay = {};
    entries.forEach(function (e) {
      var key = e.date.slice(0, 10);
      (byDay[key] = byDay[key] || []).push(e);
    });
    var html = "";
    Object.keys(byDay).sort().reverse().forEach(function (key) {
      html += '<div class="patch-day"><h3>' + dayLabel(key) + "</h3><ul>";
      byDay[key].forEach(function (e) {
        html +=
          "<li>" +
          '<span class="repo-tag ' + e.repo + '">' + e.repo + "</span>" +
          '<span class="msg">' + escapeHtml(e.message) + "</span>" +
          '<a href="' + e.url + '" title="' + escapeHtml(e.sha) + '">' + e.short_sha + "</a>" +
          "</li>";
      });
      html += "</ul></div>";
    });
    host.innerHTML = html;
  }

  function escapeHtml(s) {
    return s.replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }

  function loadPatchNotes() {
    var host = document.getElementById("patch-notes-list");
    if (!host) return;
    fetch("data/patch-notes.json")
      .then(function (r) {
        if (!r.ok) throw new Error("no patch notes file");
        return r.json();
      })
      .then(function (data) {
        state.entries = data.entries || [];
        render();
      })
      .catch(function () {
        host.innerHTML = '<p class="muted">Patch notes could not be loaded. See the commit history on GitHub instead.</p>';
      });
  }

  document.querySelectorAll("#patch-filters .chip").forEach(function (chip) {
    chip.addEventListener("click", function () {
      document.querySelectorAll("#patch-filters .chip").forEach(function (c) { c.classList.remove("active"); });
      chip.classList.add("active");
      state.filter = chip.getAttribute("data-repo");
      render();
    });
  });

  loadStatus();
  loadPatchNotes();
})();
